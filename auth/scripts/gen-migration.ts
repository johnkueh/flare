// Writes migrations/better_auth.sql: the tables Better Auth needs for
// flareAuth's options, from an empty database. Better Auth's CLI can't
// reach D1, so the SQL is generated here and applied like any migration.
// Re-run after changing plugins or Better Auth's version.
//
//   pnpm gen:migration

import { writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { flareAuthOptions, type FlareAuthEnv } from "../src/index";

const env = { BETTER_AUTH_SECRET: "x".repeat(32), BETTER_AUTH_URL: "http://localhost" } as FlareAuthEnv;
const options = { ...flareAuthOptions(env), database: new DatabaseSync(":memory:") };
const { compileMigrations } = await getMigrations(options);
const sql = (await compileMigrations())
  .replace(/^create table "(\w+)"/gim, 'CREATE TABLE IF NOT EXISTS "$1"')
  .replace(/^create index "(\w+)"/gim, 'CREATE INDEX IF NOT EXISTS "$1"');
const header = "-- Better Auth's tables for @flare/auth. Generated by scripts/gen-migration.ts; don't edit.\n\n";
writeFileSync(new URL("../migrations/better_auth.sql", import.meta.url), `${header}${sql.trim()}\n`);
