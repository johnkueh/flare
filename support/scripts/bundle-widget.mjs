// Copies widget/*.{js,css} into src/widget-assets.ts as strings, so the Worker serves them with no
// build step. Run after editing anything in widget/: `node scripts/bundle-widget.mjs`.
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) => readFileSync(new URL(`../widget/${name}`, import.meta.url), "utf8");
const out = `// Generated by scripts/bundle-widget.mjs from widget/. Don't edit by hand.
export const LOADER_JS = ${JSON.stringify(read("loader.js"))};
export const CHAT_JS = ${JSON.stringify(read("chat.js"))};
export const CHAT_CSS = ${JSON.stringify(read("chat.css"))};
`;
writeFileSync(new URL("../src/widget-assets.ts", import.meta.url), out);
