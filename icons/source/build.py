"""Build the house icons from icons.py into every platform's format.

    python3 -m pip install skia-pathops picosvg
    python3 icons/source/build.py

Writes (all generated, don't edit by hand):
  icons/icons.json                          name, group, outline + fill path data
  icons/svg/{outline,fill}/<name>.svg       plain SVG, fill="currentColor"
  icons/react/index.tsx                     <CloseIcon variant="fill" size={20} />
  icons/react-native/index.tsx              same API on react-native-svg
  swift/Sources/HouseIcons/...              asset catalog + HouseIcon enum (SPM product HouseIcons)
  kotlin/src/main/res/drawable/house_*.xml  vector drawables (R.drawable.house_close, house_close_fill)
  icons/preview.html                        the preview sheet
"""
import json, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from engine import compile_layers, to_d  # noqa: E402
from icons import ICONS, GROUPS  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
ICONS_DIR = os.path.join(ROOT, 'icons')
GENERATED = 'Generated by icons/source/build.py. Do not edit.'


def pascal(name):
    return ''.join(p.capitalize() for p in name.split('-'))


def camel(name):
    p = pascal(name)
    return p[0].lower() + p[1:]


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)


def compile_all():
    grouped = {n: g for g, names in GROUPS.items() for n in names}
    missing = set(ICONS) - set(grouped)
    assert not missing, f'icons without a group: {missing}'
    out = []
    for name in grouped:
        spec = ICONS[name]
        out.append({
            'name': name,
            'group': grouped[name],
            'outline': to_d(compile_layers(spec['o'], 'outline', spec.get('t'))),
            'fill': to_d(compile_layers(spec.get('f', spec['o']), 'fill', spec.get('t'))),
        })
    return out


def svg_file(d):
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="currentColor"><path d="{d}"/></svg>\n'


def emit_svg(icons):
    for v in ('outline', 'fill'):
        shutil.rmtree(os.path.join(ICONS_DIR, 'svg', v), ignore_errors=True)
        for i in icons:
            write(os.path.join(ICONS_DIR, 'svg', v, f"{i['name']}.svg"), svg_file(i[v]))


def emit_react(icons):
    rows = '\n'.join(
        f"export const {pascal(i['name'])}Icon = icon('{i['name']}', '{i['outline']}', '{i['fill']}');" for i in icons)
    names = ' | '.join(f"'{i['name']}'" for i in icons)
    write(os.path.join(ICONS_DIR, 'react', 'index.tsx'), f'''// {GENERATED}
import {{ forwardRef, type SVGProps }} from 'react';

export type IconVariant = 'outline' | 'fill';
export type IconName = {names};
export type IconProps = Omit<SVGProps<SVGSVGElement>, 'ref'> & {{
  variant?: IconVariant;
  size?: number | string;
  title?: string;
}};

function icon(name: IconName, outline: string, fill: string) {{
  const Icon = forwardRef<SVGSVGElement, IconProps>(({{ variant = 'outline', size = 24, title, ...props }}, ref) => (
    <svg
      ref={{ref}}
      xmlns="http://www.w3.org/2000/svg"
      width={{size}}
      height={{size}}
      viewBox="0 0 24 24"
      fill="currentColor"
      aria-hidden={{title ? undefined : true}}
      role={{title ? 'img' : undefined}}
      data-icon={{name}}
      {{...props}}
    >
      {{title ? <title>{{title}}</title> : null}}
      <path d={{variant === 'fill' ? fill : outline}} />
    </svg>
  ));
  Icon.displayName = `${{name}} icon`;
  return Icon;
}}

{rows}
''')


def emit_react_native(icons):
    rows = '\n'.join(
        f"export const {pascal(i['name'])}Icon = icon('{i['name']}', '{i['outline']}', '{i['fill']}');" for i in icons)
    names = ' | '.join(f"'{i['name']}'" for i in icons)
    write(os.path.join(ICONS_DIR, 'react-native', 'index.tsx'), f'''// {GENERATED}
import Svg, {{ Path, type SvgProps }} from 'react-native-svg';

export type IconVariant = 'outline' | 'fill';
export type IconName = {names};
export type IconProps = SvgProps & {{
  variant?: IconVariant;
  size?: number;
}};

function icon(name: IconName, outline: string, fill: string) {{
  function Icon({{ variant = 'outline', size = 24, color = 'currentColor', ...props }}: IconProps) {{
    return (
      <Svg width={{size}} height={{size}} viewBox="0 0 24 24" fill={{color}} {{...props}}>
        <Path d={{variant === 'fill' ? fill : outline}} />
      </Svg>
    );
  }}
  Icon.displayName = `${{name}} icon`;
  return Icon;
}}

{rows}
''')


def emit_swift(icons):
    base = os.path.join(ROOT, 'swift', 'Sources', 'HouseIcons')
    cat = os.path.join(base, 'Resources', 'HouseIcons.xcassets')
    shutil.rmtree(cat, ignore_errors=True)
    write(os.path.join(cat, 'Contents.json'), json.dumps({'info': {'author': 'xcode', 'version': 1}}, indent=2) + '\n')
    for i in icons:
        for v in ('outline', 'fill'):
            asset = i['name'] if v == 'outline' else f"{i['name']}.fill"
            d = os.path.join(cat, f'{asset}.imageset')
            write(os.path.join(d, f'{asset}.svg'), svg_file(i[v]).replace('currentColor', '#000000'))
            write(os.path.join(d, 'Contents.json'), json.dumps({
                'images': [{'filename': f'{asset}.svg', 'idiom': 'universal'}],
                'info': {'author': 'xcode', 'version': 1},
                'properties': {'preserves-vector-representation': True, 'template-rendering-intent': 'template'},
            }, indent=2) + '\n')
    cases = '\n'.join(f'    case {camel(i["name"])} = "{i["name"]}"' for i in icons)
    write(os.path.join(base, 'HouseIcon.swift'), f'''// {GENERATED}
import SwiftUI
#if canImport(UIKit)
import UIKit
#endif

/// The house icon set: 24pt glyphs, each in an outline and a fill variant.
/// Both are template images, so they take the foreground colour.
///
///     HouseIcon.close.image()
///     HouseIcon.heart.image(.fill).foregroundStyle(.red)
public enum HouseIcon: String, CaseIterable, Sendable {{
{cases}

    public enum Variant: Sendable {{ case outline, fill }}

    /// The asset catalog name, e.g. "close" or "close.fill".
    public func assetName(_ variant: Variant = .outline) -> String {{
        variant == .fill ? "\\(rawValue).fill" : rawValue
    }}

    public func image(_ variant: Variant = .outline) -> Image {{
        Image(assetName(variant), bundle: .module)
    }}

    #if canImport(UIKit)
    public func uiImage(_ variant: Variant = .outline) -> UIImage? {{
        UIImage(named: assetName(variant), in: .module, with: nil)?.withRenderingMode(.alwaysTemplate)
    }}
    #endif
}}
''')


def android_path(d):
    return d.replace(',', ' ')


def emit_android(icons):
    res = os.path.join(ROOT, 'kotlin', 'src', 'main', 'res', 'drawable')
    os.makedirs(res, exist_ok=True)
    for f in os.listdir(res):
        if f.startswith('house_'):
            os.remove(os.path.join(res, f))
    for i in icons:
        key = i['name'].replace('-', '_')
        for v in ('outline', 'fill'):
            fname = f'house_{key}.xml' if v == 'outline' else f'house_{key}_fill.xml'
            write(os.path.join(res, fname), f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FF000000"
        android:pathData="{android_path(i[v])}" />
</vector>
''')


def emit_json(icons):
    write(os.path.join(ICONS_DIR, 'icons.json'), json.dumps(icons, indent=1) + '\n')


def emit_preview(icons):
    usage_path = os.path.join(ICONS_DIR, 'usage', 'ranked.json')
    usage = {}
    if os.path.exists(usage_path):
        for i, (name, uses, apps) in enumerate(json.load(open(usage_path)), 1):
            usage[name] = {'rank': i, 'uses': uses, 'apps': apps}
    data = [{**i, **usage.get(i['name'], {})} for i in icons]
    tpl = open(os.path.join(HERE, 'preview.template.html')).read()
    write(os.path.join(ICONS_DIR, 'preview.html'), tpl.replace('/*ICONS*/[]', json.dumps(data, separators=(',', ':'))))


if __name__ == '__main__':
    icons = compile_all()
    emit_json(icons)
    emit_svg(icons)
    emit_react(icons)
    emit_react_native(icons)
    emit_swift(icons)
    emit_android(icons)
    emit_preview(icons)
    print(f'{len(icons)} icons, {2 * len(icons)} glyphs')
